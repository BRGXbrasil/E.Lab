CREATE TABLE records (id TEXT PRIMARY KEY, kind TEXT NOT NULL, data TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 1, updated_at TEXT NOT NULL, updated_by TEXT NOT NULL);
CREATE INDEX records_kind ON records(kind);
CREATE TABLE members (email TEXT PRIMARY KEY, user_id TEXT UNIQUE, name TEXT NOT NULL, role TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE workspace (id INTEGER PRIMARY KEY CHECK(id=1), owner_id TEXT NOT NULL UNIQUE);
CREATE TABLE audit (id TEXT PRIMARY KEY, record_id TEXT NOT NULL, kind TEXT NOT NULL, action TEXT NOT NULL, actor TEXT NOT NULL, at TEXT NOT NULL, data TEXT NOT NULL);
CREATE INDEX audit_at ON audit(at);
